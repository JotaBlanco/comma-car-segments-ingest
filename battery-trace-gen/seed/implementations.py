def _first_env(names):
    for name in names:
        value = os.environ.get(name, "").strip()
        if value:
            return value
    raise RuntimeError(f"none of {names} is set, so the lake cannot be reached")


def _query(sql):
    """Run one statement against QuixLake and read its CSV answer."""
    response = requests.post(
        _first_env(URL_VARIABLES).rstrip("/") + "/query",
        params={"union_by_name": "true"},
        data=sql.encode("utf-8"),
        headers={
            "Authorization": "Bearer " + _first_env(TOKEN_VARIABLES),
            "Content-Type": "text/plain",
            "Accept": "text/csv",
        },
        timeout=TIMEOUT_SECONDS,
    )
    response.raise_for_status()
    return list(csv.DictReader(io.StringIO(response.text)))


def _series(run_id, table):
    """`{signal: (timestamps in ms, values)}` for this test case's signals."""
    names = ", ".join("'" + name + "'" for name in SIGNALS)
    rows = _query(
        "SELECT ts_ms, signal, value FROM " + table
        + " WHERE run_id = '" + run_id.replace("'", "''") + "'"
        + " AND signal IN (" + names + ") ORDER BY ts_ms"
    )
    series = {}
    for row in rows:
        stamps, values = series.setdefault(row["signal"], ([], []))
        stamps.append(float(row["ts_ms"]))
        values.append(float(row["value"]))
    return {
        name: (np.asarray(stamps), np.asarray(values))
        for name, (stamps, values) in series.items()
    }


def _history(run_id, table):
    """Every signal on one grid, the grid in seconds, and its step.

    A CAN signal is latched, so a sample of another frame reads as the last
    value at or before the instant. Interpolating would invent a state the bus
    never held.
    """
    series = _series(run_id, table)
    missing = [name for name in SIGNALS if name not in series]
    if missing:
        raise LookupError(f"run {run_id} carries none of {missing} in {table}")

    grid = series[SIGNALS[0]][0]
    history = {}
    for name in SIGNALS:
        stamps, values = series[name]
        index = np.clip(
            np.searchsorted(stamps, grid, side="right") - 1, 0, len(values) - 1
        )
        history[name] = values[index]
    times = (grid - grid[0]) / 1000.0
    return history, times, float(np.median(np.diff(times)))


