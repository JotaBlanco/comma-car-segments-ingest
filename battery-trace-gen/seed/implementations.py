def _literal(value) -> str:
    """Render one Python literal. JSON and Python agree on lists and dicts here."""
    return json.dumps(value, indent=4)


def render(tc_id: str) -> str:
    """The whole module source of one test implementation."""
    case = CASES[tc_id]
    spec = sources.test_specs()[tc_id]
    states = "".join(
        f"\n#: `BMS_State` = {BMS_STATE[name]} (`controller/state_machine.py`).\n"
        f"{name} = {BMS_STATE[name]}\n"
        for name in case.states
    )
    return _TEMPLATE.substitute(
        tc_id=tc_id,
        title=spec["title"],
        req_ids=", ".join(spec["covers_req_ids"]),
        req_id_list=_literal(list(spec["covers_req_ids"])),
        signal_list=_literal(list(case.signals)),
        limits=_literal(case.limits),
        states=states,
        rule=case.rule,
        measure=case.measure,
        passes=case.passes,
    )


def write_all(out_dir: Path = OUT_DIR) -> dict[str, Path]:
    """Write the ten modules. Returns `{tc_id: path}`."""
    out_dir.mkdir(parents=True, exist_ok=True)
    written = {}
    for tc_id in sorted(CASES):
        path = out_dir / f"{tc_id}.py"
        path.write_text(render(tc_id), encoding="utf-8")
        written[tc_id] = path
    return written


def upload_all(out_dir: Path = OUT_DIR) -> dict[str, dict]:
    """Render, then POST each module to its definition. Returns the answers."""
    return {
        tc_id: push.implementation(tc_id, path)
        for tc_id, path in write_all(out_dir).items()
    }
